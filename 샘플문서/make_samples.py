PAGE_W, PAGE_H = A4


def wrap_chars(c, text, width, size=11):
    lines = []
    for raw in text.split('\n'):
        line = ''
        for ch in raw:
            if c.stringWidth(line + ch, 'K', size) <= width:
                line += ch
            else:
                lines.append(line)
                line = ch
        if line:
            lines.append(line)
    return lines


class Pdf:
    def __init__(self, path):
        self.c = canvas.Canvas(path, pagesize=A4)
        self.c.setFont('K', 11)
        self.y = PAGE_H - 60

    def _advance(self, needed=16):
        if self.y - needed < 50:
            self.c.showPage()
            self.c.setFont('K', 11)
            self.y = PAGE_H - 60

    def title(self, text, size=18):
        self._advance(28)
        self.c.setFont('K', size)
        self.c.drawCentredString(PAGE_W / 2, self.y, text)
        self.y -= 30
        self.c.setFont('K', 11)

    def para(self, text, size=11, color=None):
        for line in wrap_chars(self.c, text, PAGE_W - 100, size):
            self._advance(size + 6)
            self.c.setFont('K', size)
            if color is not None:
                self.c.setFillColor(color)
            self.c.drawString(50, self.y, line)
            if color is not None:
                self.c.setFillColorRGB(0, 0, 0)
            self.y -= size + 6

    def hidden(self, text):
        """흰 글씨로 그려 사람 눈에는 안 보이고 텍스트 레이어에만 남긴다."""
        self.c.setFont('K', 6)
        self.c.setFillColor(white)
        for line in wrap_chars(self.c, text, PAGE_W - 100, 6):
            self._advance(8)
            self.c.drawString(50, self.y, line)
            self.y -= 8
        self.c.setFillColorRGB(0, 0, 0)
        self.c.setFont('K', 11)

    def save(self):
        self.c.save()


