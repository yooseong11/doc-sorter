def make_hwpx():
    # R1은 hwpx 추출기를 지원하지 않는다. 확장자만 맞추면 목록에서 빠지지 않고
    # 미분류로 넘어가는지만 확인하면 되므로 최소 구조로 둔다.
    path = os.path.join(OUT, '경조사_휴가신청서.hwpx')
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('[Content_Types].xml', (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"/>'
        ))
        z.writestr('contents/header.xml', (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<hwpx:header xmlns:hwpx="http://www.hancom.co.kr/hwpml/2016/HwpMl"/>'
        ))
    print('  (hwpx는 R1 미지원 확인용 최소 구조)')


